#!/usr/bin/env python3
"""Phase D summary: python tests/smartbot/phaseD_summary.py  -> out/phaseD/phaseD_summary.md / .json"""
import csv, glob, json, os, re, statistics as st, collections

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out", "phaseD")
WRE = re.compile(r"wager:([\w-]+)\|x(\d)\|(\w*)\|why=([^|]*)\|.*?gold=(-?\d+)")
CLS = ["warrior", "ranger", "mage"]
NAME = re.compile(r"^(legacy|typical|geared)_(warrior|ranger|mage)_(.+)\.csv$")
ODDS = {}
try:
    atlas = json.load(open(os.path.join(HERE, "..", "..", "data", "atlas.json"), encoding="utf-8"))
    def walk(o):
        if isinstance(o, dict):
            if "odds" in o and "id" in o:
                ODDS[o["id"]] = float(o["odds"])
            for v in o.values(): walk(v)
        elif isinstance(o, list):
            for v in o: walk(v)
    walk(atlas)
except Exception:
    pass


def load():
    D = collections.defaultdict(list)   # (cell, gear, class) -> rows
    for fn in glob.glob(os.path.join(OUT, "*.csv")):
        b = os.path.basename(fn)
        if b.endswith("_perf.csv") or "_smoke" in b:
            continue
        m = NAME.match(b)
        if not m:
            continue
        g, c, cell = m.groups()
        D[(cell, g, c)] = list(csv.DictReader(open(fn, encoding="utf-8")))
    return D


def mean(x):
    return st.mean(x) if x else float("nan")


def stats(rs):
    w = [r for r in rs if r["outcome"] == "boss_killed"]
    fight = [float(r["clear_time"]) - float(r["time_to_boss"]) for r in w]
    causes = collections.Counter((r["cause_of_death"] or r["top_damage"].split(":")[0])[:40] for r in rs if r["outcome"] == "died")
    return {"n": len(rs), "wins": len(w), "deaths": sum(1 for r in rs if r["outcome"] == "died"),
            "clear": mean([float(r["clear_time"]) for r in w]), "fight": mean(fight),
            "fight_med": st.median(fight) if fight else float("nan"),
            "taken": mean([float(r["damage_taken"]) for r in rs]), "life": mean([float(r["max_life"]) for r in rs]),
            "causes": causes.most_common(3)}


def pct(a, b):
    return f"{100.0 * a / b:.0f}%" if b else "-"


def main():
    D = load()
    J = {"cells": {}, "wager": {}}
    L = ["# Phase D summary (generated by phaseD_summary.py)\n"]
    # --- Rot and Warden / side cells
    def block(title, cells):
        L.append(f"\n## {title}\n")
        L.append("| Cell | Gear | All wins | Warrior | Ranger | Mage | Deaths w/r/m | Fight s w/r/m (wins) | Damage taken w/r/m | Top death causes |")
        L.append("|---|---|---|---|---|---|---|---|---|---|")
        for cell in cells:
            for g in ("legacy", "typical", "geared"):
                S = {c: stats(D[(cell, g, c)]) for c in CLS if (cell, g, c) in D}
                if not S:
                    continue
                n = sum(s["n"] for s in S.values()); w = sum(s["wins"] for s in S.values())
                f = lambda c, k, fmt="%.0f": (fmt % S[c][k]) if c in S else "-"
                causes = collections.Counter()
                for s in S.values():
                    causes.update(dict(s["causes"]))
                L.append(f"| {cell} | {g} | {w}/{n} ({pct(w, n)}) | " + " | ".join(f"{S[c]['wins']}/{S[c]['n']}" if c in S else "-" for c in CLS)
                         + " | " + "/".join(f(c, "deaths") for c in CLS) + " | " + "/".join(f(c, "fight", "%.1f") for c in CLS)
                         + " | " + "/".join(f(c, "taken") for c in CLS) + " | " + ", ".join(f"{k} x{v}" for k, v in causes.most_common(3)) + " |")
                for c, s in S.items():
                    J["cells"][f"{cell}|{g}|{c}"] = s
    block("Rot dial (ring 3 hex 3,0, L50)", ["rot3", "rot4", "rot4p", "rot4p_s1900", "rot5p"])
    block("Layer Wardens under Rot", [f"W{r}_rot{x}" for r in (1, 2, 3) for x in (3, 4, 5)])
    block("Side cells: Archon Velis at Rot 4, forced builds (typical)",
          ["W3_rot4_" + b for b in ("r_glass", "r_perfect_aim", "r_far_aim", "r_wind", "none", "m_glacial")])
    # --- Wager
    W = collections.defaultdict(lambda: collections.defaultdict(list))
    for (cell, g, c), rs in D.items():
        if not cell.startswith("wager_"):
            continue
        for r in rs:
            m = WRE.search(r["notes"])
            if m:
                W[m.group(1)][c].append((m.group(3), int(m.group(5)), m.group(4), r["outcome"]))
    if W:
        L.append("\n## Collector's Wager (typical, rings 2 + 3, stake 1x)\n")
        L.append("| Bet | Odds | All win | Warrior | Ranger | Mage | Net gold per stake | Odds for EV +15% | Top loss reasons |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for bet in sorted(W):
            allr = [x for c in CLS for x in W[bet].get(c, [])]
            won = sum(1 for x in allr if x[0] == "won"); n = len(allr)
            # stake: a loss costs the stake; a win nets stake x odds (Rot 0, so no rot bonus)
            stakes = [-x[1] for x in allr if x[1] < 0] or [x[1] / ODDS[bet] for x in allr if x[1] > 0 and ODDS.get(bet)]
            stake = st.median(stakes) if stakes else 1
            ev = mean([x[1] / stake for x in allr]) if allr else 0
            p = won / n if n else 0
            odds_t = (1.15 - p) / p if p else float("inf")
            why = collections.Counter(x[2] for x in allr if x[0] != "won").most_common(2)
            L.append(f"| {bet} | {ODDS.get(bet, '?')} | {won}/{n} ({pct(won, n)}) | "
                     + " | ".join(pct(sum(1 for x in W[bet].get(c, []) if x[0] == 'won'), len(W[bet].get(c, []))) for c in CLS)
                     + f" | {ev:+.2f} | {odds_t:.2f} | " + ", ".join(f"{k} x{v}" for k, v in why) + " |")
            J["wager"][bet] = {"n": n, "won": won, "ev": ev, "odds_now": ODDS.get(bet), "odds_ev15": odds_t,
                               "by_class": {c: [sum(1 for x in W[bet].get(c, []) if x[0] == 'won'), len(W[bet].get(c, []))] for c in CLS}}
    # --- errors
    logs = glob.glob(os.path.join(OUT, "*.csv.log"))
    errs = [os.path.basename(l) for l in logs if "SCRIPT ERROR" in open(l, errors="replace").read() and "_smoke" not in l]
    L.append(f"\n{len(logs)} batch logs, SCRIPT ERROR in: {', '.join(errs) if errs else 'none'}\n")
    open(os.path.join(OUT, "phaseD_summary.md"), "w", encoding="utf-8").write("\n".join(L))
    json.dump(J, open(os.path.join(OUT, "phaseD_summary.json"), "w"), indent=1, default=str)
    print("\n".join(L))


if __name__ == "__main__":
    main()
